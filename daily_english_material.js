filterTopic = function (topic) {
  activeDeck = words
    .map((w, i) => w[3] === topic ? i : null)
    .filter(i => i !== null);

  deckPosition = 0;

  if (activeDeck.length) {
    index = activeDeck[0];
    openPage('cards');
    document.getElementById('topic-note').textContent =
      'Открыта тема: ' + topic + ' · ' + activeDeck.length + ' карточек.';
  }
};

nextCard = function () {
  const list = activeDeck || words.map((_, i) => i);
  deckPosition = (deckPosition + 1) % list.length;
  index = list[deckPosition];
  renderCard();
};

prevCard = function () {
  const list = activeDeck || words.map((_, i) => i);
  deckPosition = (deckPosition - 1 + list.length) % list.length;
  index = list[deckPosition];
  renderCard();
};

